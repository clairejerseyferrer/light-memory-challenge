create sequence if not exists public.game_session_number_seq start with 1;
create table if not exists public.game_sessions (
 id uuid primary key,
 session_number bigint not null unique default nextval('public.game_session_number_seq'),
 codename varchar(24) not null check (char_length(trim(codename)) between 2 and 24),
 device_id text not null default 'ESP32-001',
 status text not null default 'waiting' check (status in ('waiting','countdown','playing','completed','abandoned')),
 created_at timestamptz not null default now(), start_at timestamptz, started_at timestamptz, completed_at timestamptz
);
create index if not exists idx_game_sessions_device_status on public.game_sessions(device_id,status,created_at desc);
create index if not exists idx_game_sessions_codename on public.game_sessions(lower(codename),created_at desc);
create table if not exists public.game_results (
 session_id uuid primary key references public.game_sessions(id) on delete cascade,
 score integer not null check (score >= 0), highest_level integer not null check (highest_level >= 1),
 mistakes integer not null check (mistakes >= 0), total_rounds integer not null check (total_rounds >= 0),
 correct_rounds integer not null check (correct_rounds >= 0 and correct_rounds <= total_rounds),
 accuracy numeric(5,2) not null check (accuracy between 0 and 100),
 game_duration_seconds numeric(10,2) not null check (game_duration_seconds >= 0),
 lives_remaining integer not null check (lives_remaining between 0 and 3),
 avg_response_time_ms numeric(10,2), fastest_response_time_ms numeric(10,2), slowest_response_time_ms numeric(10,2),
 round_data jsonb not null default '[]'::jsonb, analysis jsonb not null default '{}'::jsonb, saved_at timestamptz not null default now()
);
alter table public.game_sessions enable row level security;
alter table public.game_results enable row level security;

comment on column public.game_results.round_data is
'Per-level Intelligent System telemetry: sequence attempts, correct sequences, failed sequences, accuracy, whole-sequence response-time summaries, sequence length, and incorrect press position details.';

-- Adaptive difficulty audit trail. One immutable decision per session/level.
-- Fresh installs: this file creates the final shape. Existing databases: run
-- migrations/migration_adaptive_difficulty.sql, then migrations/migration_adaptive_response_time.sql.
create table if not exists public.game_adaptive_events (
    id bigint generated by default as identity primary key,
    session_id uuid not null references public.game_sessions(id) on delete cascade,
    completed_level integer not null check (completed_level between 1 and 20),
    decision jsonb not null,
    applied boolean default null,
    actual_sequence_length integer,
    actual_response_time_allowance_ms integer check (actual_response_time_allowance_ms between 8000 and 45000),
    created_at timestamptz not null default now(),
    policy_version text,
    classification text,
    recommended_adjustment_ms integer,
    previous_adjustment_ms integer,
    recommended_new_adjustment_ms integer,
    previous_response_time_allowance_ms integer,
    recommended_response_time_allowance_ms integer,
    actual_response_time_adjustment_ms integer,
    applied_at timestamptz,
    applied_matches_recommendation boolean,
    sequence_progression_verified boolean,
    unique(session_id, completed_level),
    constraint game_adaptive_events_actual_sequence_length_check
        check (actual_sequence_length is null or actual_sequence_length between 2 and 30),
    constraint game_adaptive_events_v2_ranges_check check (
        (recommended_new_adjustment_ms is null or recommended_new_adjustment_ms between -4000 and 10000)
        and (previous_adjustment_ms is null or previous_adjustment_ms between -4000 and 10000)
        and (actual_response_time_adjustment_ms is null or actual_response_time_adjustment_ms between -4000 and 10000)
        and (recommended_response_time_allowance_ms is null or recommended_response_time_allowance_ms between 8000 and 45000)
    )
);
create index if not exists idx_game_adaptive_events_session
    on public.game_adaptive_events(session_id, completed_level);
create index if not exists idx_game_adaptive_events_policy
    on public.game_adaptive_events(policy_version);
alter table public.game_adaptive_events enable row level security;
